#!/usr/bin/env bash
# compose-probe.sh — does Compose come across with import-level edits? (PLAN.md D2)
#
# D2 assumes the Compose UI ports with its imports intact. That assumption is load-bearing: if it
# holds, M3-M7 are mostly mechanical; if it does not, the cost lands in a milestone nobody has
# reached yet. So it is checked here, before the UI is ported, rather than discovered at M6.
#
# The probe is the import set itself. Every `androidx.compose.*` / `coil3.*` / `com.nikosm.*.ui.*`
# import the upstream UI layer actually uses is written into one temporary file and compiled
# against :desktop's dependencies. An unresolved import is a compile error, so the compiler's error
# list is the answer, exactly and without interpretation.
#
# It writes a throwaway file into :desktop, compiles, prints the result, and deletes it. It never
# touches the build script: the two dependencies the probe needs are added on the command line, via
# an init script, so a clean run leaves no trace. Use --keep to leave the generated file in place
# and read it yourself.
#
#   tools/compose-probe.sh            the probe, and a summary
#   tools/compose-probe.sh --keep     and leave the generated file in :desktop
#   tools/compose-probe.sh --deps     with material3 + icons added, i.e. the post-fix answer
set -uo pipefail

UPSTREAM="${UPSTREAM:-../VoiceAssistant}"
REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$UPSTREAM/app/src/main/java/com/nikosm/voiceassistant"
PROBE_DIR="$REPO_ROOT/desktop/src/main/kotlin/com/nikosm/voiceassistant/probe"
PROBE="$PROBE_DIR/ComposeProbe.kt"
DEST_UI="$REPO_ROOT/desktop/src/main/kotlin/com/nikosm/voiceassistant"

KEEP=0; WITH_DEPS=0
for a in "$@"; do case "$a" in
  --keep) KEEP=1 ;;
  --deps) WITH_DEPS=1 ;;
esac; done

# The UI layer: every upstream file whose type face is Compose rather than the service.
UI_FILES=(
  CelestialHud.kt ChatComponents.kt FullScreenImageViewer.kt ImageWorkflowImport.kt
  MainVoiceScreen.kt ModelPicker.kt ModelScreens.kt PersonaEditor.kt RoomScreens.kt
  SettingsScreens.kt SkillScreens.kt SpontaneousScreens.kt UIComponents.kt WelcomeScreen.kt
  SharedContent.kt
)

BUILD_FILE="$REPO_ROOT/desktop/build.gradle.kts"
BUILD_BACKUP="$REPO_ROOT/build/compose-probe-build.gradle.kts.bak"
cleanup() {
  [ "$KEEP" = 1 ] || rm -f "$PROBE"
  rmdir "$PROBE_DIR" 2>/dev/null
  # Restore the build script unconditionally — including on Ctrl-C and on a failed compile. The
  # probe must not be able to leave a dependency behind that nobody chose to add.
  [ -f "$BUILD_BACKUP" ] && { mv -f "$BUILD_BACKUP" "$BUILD_FILE"; }
  return 0
}
trap cleanup EXIT

# Which tree a file is read from: OURS once it has been ported, upstream until then.
#
# This is what lets the number fall to zero. Reading upstream forever would leave the probe
# reporting the same six resolvable-by-the-port imports for the rest of the project, and a measure
# that cannot reach zero is a measure nobody looks at twice. As each UI file lands in :desktop the
# probe starts asking about the ported one, so the count is "how much UI is left", not "how much
# upstream uses Android".
src_for() { # name -> the tree to read it from
  if   [ -f "$DEST_UI/$1" ];   then echo "$DEST_UI/$1"
  elif [ -f "$SRC/$1" ];       then echo "$SRC/$1"
  fi
}
theme_src_for() {
  if   [ -d "$DEST_UI/ui/theme" ]; then echo "$DEST_UI/ui/theme"
  elif [ -d "$SRC/ui/theme" ];     then echo "$SRC/ui/theme"
  fi
}

mkdir -p "$PROBE_DIR"
{
  echo "// TEMPORARY PROBE — generated by tools/compose-probe.sh, not part of the build."
  echo "// Every import below is one the UI layer uses, taken from OUR tree where a file has been"
  echo "// ported and from upstream's where it has not. An unresolved import is work still to do."
  echo "package com.nikosm.voiceassistant.probe"
  echo
  # Only the imports are sorted. Sorting the whole block put `package` after them, because `p`
  # sorts after `i`, and the file then failed to parse as a syntax error rather than as the
  # unresolved import it was meant to report.
  {
    for f in "${UI_FILES[@]}"; do
      file="$(src_for "$f")"
      [ -n "$file" ] || { echo "// MISSING upstream and here: $f" >&2; continue; }
      grep '^import \(androidx\.compose\|android\.\|coil3\|com\.nikosm\.voiceassistant\.ui\)' "$file" || true
    done
    # The theme package is its own directory, upstream and here.
    theme="$(theme_src_for)"
    [ -n "$theme" ] && { grep -rh '^import \(androidx\.compose\|android\.\|coil3\)' "$theme" || true; }
  } | sort -u
} > "$PROBE"

echo "probe     : $PROBE"
echo "imports   : $(grep -c '^import ' "$PROBE")"
echo "files     : ${#UI_FILES[@]} upstream UI files + ui/theme/"
echo

if [ "$WITH_DEPS" = 1 ]; then
  # Through the Compose *plugin's* accessors, not by naming Maven coordinates here. CMP versions
  # `material3` on its own release line, so a coordinate written into this script would be a guess
  # that silently turns a resolvable import into a reported failure — the worst kind of wrong
  # answer for a probe whose whole job is to be believed. The backup is restored by the trap.
  mkdir -p "$(dirname "$BUILD_BACKUP")"
  cp "$BUILD_FILE" "$BUILD_BACKUP"
  awk '{ print; if ($0 ~ /^[[:space:]]*implementation\(compose\.desktop\.currentOs\)$/)
         print "    implementation(compose.material3)\n    implementation(compose.materialIconsExtended)" }' \
    "$BUILD_BACKUP" > "$BUILD_FILE"
  grep -q 'compose.materialIconsExtended' "$BUILD_FILE" || {
    echo "could not add the probe dependencies — aborting rather than reporting a false answer" >&2
    exit 2
  }
  echo "note      : --deps, so material3 and material-icons-extended are on the compile classpath"
  echo "            (desktop/build.gradle.kts is backed up and restored; the tree is untouched)"
  echo
fi

OUT="$(cd "$REPO_ROOT" && ./gradlew :desktop:compileKotlin -q 2>&1 | grep '^e: ' || true)"
if [ -z "$OUT" ]; then
  echo "RESULT: every import resolves. D2 holds for this set."
  exit 0
fi

# Report the IMPORT, not the compiler's symbol. "Unresolved reference 'ui'" is not actionable;
# "import androidx.compose.ui.platform.LocalContext" is, and it is the thing the port has to change.
printf '%s\n' "$OUT" | sed "s|.*ComposeProbe.kt:||" | sed 's/:.*//' | grep -E '^[0-9]+$' | sort -un \
  > /tmp/compose-probe-lines.txt
# awk rather than `sed -n "$(paste -sd, …)p"`: sed reads `6,7,75` as ONE range with a trailing
# command, not as a list of lines, so the comma form silently extracts nothing.
awk -v list="$(paste -sd, /tmp/compose-probe-lines.txt)" \
    'BEGIN { n = split(list, a, ","); for (i = 1; i <= n; i++) want[a[i]] = 1 }
     want[FNR] && /^import /' "$PROBE" | sort -u | sed 's/^/  /' > /tmp/compose-probe-imports.txt

echo "RESULT: $(wc -l < /tmp/compose-probe-lines.txt | tr -d ' ') import(s) do not resolve:"
cat /tmp/compose-probe-imports.txt
echo
echo "Each one is one of four things, and only the first two are real work:"
echo "  androidx.compose.ui.platform.LocalContext / LocalConfiguration"
echo "        -> Android-only Compose APIs. LocalContext's callers want a Context for a Toast, a"
echo "           clipboard or a file picker, and every one of those has a seam already;"
echo "           LocalConfiguration is the device's size, which on a desktop is the window's."
echo "  material3 dynamic-color helpers (dynamicDarkColorScheme / dynamicLightColorScheme)"
echo "        -> Android's Material You, which reads the wallpaper through a Context. No desktop"
echo "           counterpart; the theme's own palette is the fallback and already exists."
echo "  android.*"
echo "        -> the seam that already replaced it; nothing new to design."
echo "  coil3 / material3 / material.icons"
echo "        -> a dependency declaration, not a port. Run with --deps to confirm."
exit 1
